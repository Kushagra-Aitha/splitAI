// The package does not export its asset folder, so read it from node_modules.
const assets = new URL('../node_modules/@phosphor-icons/core/assets/light/', import.meta.url).pathname;
const bodies = {};
for (const phosphor of new Set(Object.values(NAMES))) {
  const svg = readFileSync(path.join(assets, `${phosphor}-light.svg`), 'utf8');
  bodies[phosphor] = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim();
}

const out = `// Generated by scripts/build-icons.mjs from @phosphor-icons/core (Light).
// Do not edit by hand: add a name to the script and run \`npm run icons\`.
export const PHB = ${JSON.stringify(bodies, null, 2)};

export const PHN = ${JSON.stringify(NAMES, null, 2)};
`;
writeFileSync(new URL('../src/icons/phosphor.js', import.meta.url), out);
console.log(`Wrote ${Object.keys(NAMES).length} names → ${Object.keys(bodies).length} Phosphor Light icons.`);
